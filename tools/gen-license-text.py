#!/usr/bin/env python3
"""Generate src/setup/license_text.c (the text Setup.exe shows) from
LICENSE-MIT and LICENSE-APACHE.  Run after changing either file; `make dist`
(installer/make-dist.sh) checks that the generated file is current.

    tools/gen-license-text.py [--check]
"""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_path = os.path.join(root, "src", "setup", "license_text.c")


def c_string(text):
    lines = []
    for line in text.split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    "%s\\r\\n"' % esc)
    return "\n".join(lines)


def generate():
    parts = []
    for name in ("LICENSE-MIT", "LICENSE-APACHE"):
        with open(os.path.join(root, name), encoding="utf-8") as f:
            text = f.read().replace("\r\n", "\n").rstrip("\n")
        # Setup.exe shows ANSI text: keep it to ASCII
        text = text.encode("ascii", "replace").decode("ascii").replace("\t", "    ")
        parts.append(text)
    body = ("PhotoCraft Classic is dual-licensed under the MIT License or the "
            "Apache License, Version 2.0, at your option.\n\n"
            "----- MIT License -----\n\n" + parts[0] +
            "\n\n----- Apache License 2.0 -----\n\n" + parts[1])
    return ("/* GENERATED by tools/gen-license-text.py from LICENSE-MIT and LICENSE-APACHE.\n"
            " * Do not edit. */\n"
            "const char pc_license_text[] =\n" + c_string(body) + ";\n")


def main():
    src = generate()
    if "--check" in sys.argv:
        try:
            with open(out_path, encoding="utf-8") as f:
                if f.read() == src:
                    return 0
        except FileNotFoundError:
            pass
        print("src/setup/license_text.c is out of date; run tools/gen-license-text.py", file=sys.stderr)
        return 1
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(src)
    return 0


if __name__ == "__main__":
    sys.exit(main())
