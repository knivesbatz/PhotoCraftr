#!/bin/sh
# Regenerate src/updater/trust_anchors.c from the root CA PEMs in this
# directory, using BearSSL's "brssl ta" tool.
#
#   tools/trust/regen-trust-anchors.sh [output.c] [extra.pem ...]
#
# BRSSL=/path/to/brssl selects an existing brssl binary.  Otherwise a full
# BearSSL checkout (BEARSSL_TREE, default: a fresh clone of
# https://www.bearssl.org/git/BearSSL at the vendored commit) is built in a
# temporary directory.  third_party/bearssl only carries src/ and inc/,
# not the tools/ directory brssl is built from.
#
# Extra PEM files after the output name are appended as additional anchors;
# that is ONLY used by the native network test (tests/integration), which
# needs the container's TLS-intercepting proxy CA.  Release builds never
# pass extra files.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
out=${1:-$root/src/updater/trust_anchors.c}
[ $# -gt 0 ] && shift
BEARSSL_COMMIT=7bea48e   # matches third_party/bearssl

if [ -z "${BRSSL:-}" ]; then
    tmp=$(mktemp -d)
    trap 'rm -rf "$tmp"' EXIT
    if [ -n "${BEARSSL_TREE:-}" ]; then
        cp -r "$BEARSSL_TREE" "$tmp/BearSSL"
    else
        git clone -q https://www.bearssl.org/git/BearSSL "$tmp/BearSSL"
        (cd "$tmp/BearSSL" && git checkout -q "$BEARSSL_COMMIT")
    fi
    make -C "$tmp/BearSSL" -s build/brssl >/dev/null
    BRSSL=$tmp/BearSSL/build/brssl
fi

# Order is irrelevant to BearSSL; keep it stable for reproducible output.
pems="
ISRG_Root_X1.pem
ISRG_Root_X2.pem
ISRG_Root_YR.pem
ISRG_Root_YE.pem
USERTrust_RSA_Certification_Authority.pem
USERTrust_ECC_Certification_Authority.pem
Sectigo_Public_Server_Authentication_Root_R46.pem
Sectigo_Public_Server_Authentication_Root_E46.pem
DigiCert_Global_Root_G2.pem
DigiCert_Global_Root_G3.pem
"
files=""
for p in $pems; do files="$files $here/$p"; done
for p in "$@"; do files="$files $p"; done

{
    echo "/*"
    echo " * GENERATED by tools/trust/regen-trust-anchors.sh with BearSSL 'brssl ta'."
    echo " * Do not edit; edit the PEM list in tools/trust/ and regenerate."
    echo " *"
    echo " * Root CAs pinned for the updater (see docs/updater.md, 'Trust anchors'):"
    for f in $files; do
        echo " *   $(openssl x509 -in "$f" -noout -subject -nameopt oneline,-esc_msb | sed 's/^subject=//')"
        echo " *     SHA-256 $(openssl x509 -in "$f" -noout -fingerprint -sha256 | sed 's/.*=//')"
    done
    echo " */"
    echo "#include <bearssl.h>"
    echo "#include \"trust_anchors.h\""
    "$BRSSL" ta -q $files
    echo
    echo "const br_x509_trust_anchor *const pc_trust_anchors = TAs;"
    echo "const size_t pc_trust_anchors_num = TAs_NUM;"
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
